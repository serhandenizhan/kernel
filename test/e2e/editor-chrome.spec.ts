test('menüler klavyeyle gezilir: ok tuşları, → alt menüyü açar, ← kapatır, Enter seçer, Esc önce alt menüyü sonra menüyü kapatır', async () => {
  const vault = tmpVault()
  writeFileSync(join(vault, 'Not.md'), '## Bölüm\n\nmetin\n')
  const { app, win } = await launch(vault)
  await win.getByTestId('tree-row').filter({ hasText: 'Not' }).click()
  await win.locator('.kernel-editor h2').hover()
  await win.getByTestId('block-handle').click()
  const menu = win.getByRole('menu').first()
  await expect(menu).toBeVisible()
  await win.keyboard.press('ArrowDown')
  await expect(menu.getByRole('menuitem', { name: 'Dönüştür' })).toHaveAttribute('data-active', 'true')
  await win.keyboard.press('ArrowRight')
  const sub = win.locator('.submenu')
  await expect(sub).toBeVisible()
  await expect(sub.getByRole('menuitem', { name: 'Metin' })).toHaveAttribute('data-active', 'true')
  // ← alt menüyü kapatır, üst menüde kalır
  await win.keyboard.press('ArrowLeft')
  await expect(sub).toHaveCount(0)
  await expect(menu).toBeVisible()
  // Esc: önce alt menü, sonra menü
  await win.keyboard.press('ArrowRight')
  await expect(sub).toBeVisible()
  await win.keyboard.press('Escape')
  await expect(sub).toHaveCount(0)
  await expect(menu).toBeVisible()
  await win.keyboard.press('Escape')
  await expect(win.getByRole('menu')).toHaveCount(0)
  // ↓ → ↓ Enter: Başlık 2 → Başlık 1
  await win.getByTestId('block-handle').click()
  await win.keyboard.press('ArrowDown')
  await win.keyboard.press('ArrowRight')
  await win.keyboard.press('ArrowDown')
  await win.keyboard.press('Enter')
  await expect(win.locator('.kernel-editor h1')).toHaveText('Bölüm')
  await expect(win.getByRole('menu')).toHaveCount(0)
  // menü açıkken ok tuşları metni kaydırmaz: yazı değişmedi
  await expect(win.locator('.kernel-editor p').first()).toHaveText('metin')
  await app.close()
})
