const chartJson = (vault: string, file: string) => {
  const m = /```chart\n([\s\S]*?)\n```/.exec(body(vault, file))
  return m ? JSON.parse(m[1]!) : null
}

async function slashInsert(win: Page, query: string, item: string) {
  await win.keyboard.type(`/${query}`)
  await win.getByTestId('slash-item').filter({ hasText: item }).first().click()
}

test('"/" ile pasta grafik eklenir; ad, değer, renk düzenlenir; satır eklenir ve sürüklenerek sıralanır', async () => {
  const vault = tmpVault()
  writeFileSync(join(vault, 'Bütçe.md'), 'giriş\n')
  const { app, win } = await launch(vault)
  await win.getByTestId('tree-row').filter({ hasText: 'Bütçe' }).click()
  await win.getByText('giriş').click()
  await win.keyboard.press('End')
  await win.keyboard.press('Enter')
  await slashInsert(win, 'pasta', 'Pasta grafik')
  const block = win.getByTestId('chart-block')
  await expect(block.locator('.kc-slice')).toHaveCount(4)
  const editor = block.getByTestId('chart-editor')
  await expect(editor).toBeVisible()
  await editor.getByTestId('chart-row-label').first().fill('Kira')
  await editor.getByTestId('chart-row-value').first().fill('50')
  await expect.poll(() => chartJson(vault, 'Bütçe.md')?.rows?.[0]).toMatchObject({ label: 'Kira', values: [50] })
  await expect(block.locator('svg')).toContainText('Kira')
  // renk: paletten seç
  await editor.getByTestId('chart-row-color').first().click()
  await win.getByTestId('chart-swatch').nth(4).click()
  await expect.poll(() => chartJson(vault, 'Bütçe.md')?.rows?.[0]?.color).toBe('#8e6cf0')
  // satır ekle
  await editor.getByTestId('chart-add-row').click()
  await expect(block.locator('.kc-slice')).toHaveCount(5)
  // tabloda sürükle: ilk satır üçüncünün yerine
  await editor.getByTestId('chart-row-handle').first().dragTo(editor.getByTestId('chart-row').nth(2))
  await expect.poll(() => chartJson(vault, 'Bütçe.md')?.rows?.map((r: { label: string }) => r.label)?.slice(0, 3)).toEqual(['Öğe 2', 'Öğe 3', 'Kira'])
  // Bitti: panel kapanır, grafiğe tıklayınca yeniden açılır
  await editor.getByTestId('chart-done').click()
  await expect(editor).toHaveCount(0)
  await block.getByTestId('chart-edit').click()
  await expect(block.getByTestId('chart-editor')).toBeVisible()
  await app.close()
})

